<script setup lang="ts">
const colorMode = useColorMode();

const modes = ["light", "dark", "system"] as const;

const currentIndex = computed(() => modes.indexOf(colorMode.preference as (typeof modes)[number]));

function cycle() {
  colorMode.preference = modes[(currentIndex.value + 1) % modes.length];
}

const ariaLabel = computed(() => {
  const next = modes[(currentIndex.value + 1) % modes.length];
  return `Switch to ${next} mode`;
});
</script>

<template>
  <button
    type="button"
    :aria-label="ariaLabel"
    class="rounded-md p-1.5 text-muted transition-colors hover:bg-raised hover:text-primary"
    @click="cycle"
  >
    <!-- Sun — light mode -->
    <svg
      v-if="colorMode.value === 'light'"
      xmlns="http://www.w3.org/2000/svg"
      width="18"
      height="18"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      stroke-width="2"
      stroke-linecap="round"
      stroke-linejoin="round"
      aria-hidden="true"
    >
      <circle cx="12" cy="12" r="5" />
      <line x1="12" y1="1" x2="12" y2="3" />
      <line x1="12" y1="21" x2="12" y2="23" />
      <line x1="4.22" y1="4.22" x2="5.64" y2="5.64" />
      <line x1="18.36" y1="18.36" x2="19.78" y2="19.78" />
      <line x1="1" y1="12" x2="3" y2="12" />
      <line x1="21" y1="12" x2="23" y2="12" />
      <line x1="4.22" y1="19.78" x2="5.64" y2="18.36" />
      <line x1="18.36" y1="5.64" x2="19.78" y2="4.22" />
    </svg>
    <!-- Moon — dark mode -->
    <svg
      v-else-if="colorMode.value === 'dark'"
      xmlns="http://www.w3.org/2000/svg"
      width="18"
      height="18"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      stroke-width="2"
      stroke-linecap="round"
      stroke-linejoin="round"
      aria-hidden="true"
    >
      <path d="M21 12.79A9 9 0 1 1 11.21 3 7 7 0 0 0 21 12.79z" />
    </svg>
    <!-- Monitor — system -->
    <svg
      v-else
      xmlns="http://www.w3.org/2000/svg"
      width="18"
      height="18"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      stroke-width="2"
      stroke-linecap="round"
      stroke-linejoin="round"
      aria-hidden="true"
    >
      <rect x="2" y="3" width="20" height="14" rx="2" />
      <line x1="8" y1="21" x2="16" y2="21" />
      <line x1="12" y1="17" x2="12" y2="21" />
    </svg>
  </button>
</template>
